Se elige un recorrido concreto y útil (al liceo, al club, a la casa de alguien) y se hace en tres etapas: primero acompañado, después acompañado desde lejos, después solo. Cada etapa se repite hasta que sale sin dudas.
Ejercicio 1, el recorrido, por partes:
• Qué línea, dónde se toma, y hacia dónde va.
• Cuánto tarda, y a qué hora hay que salir.
• Dónde se baja, y cómo se reconoce la parada.
• Cómo se vuelve, que casi siempre es la parte que falta.
Se escribe en el celular y en un papel, las dos cosas.
Ejercicio 2, la plata y la tarjeta:
• Cargar la tarjeta, y cuánto queda.
• Plata suelta de reserva, en un lugar fijo y separado.
• Cuánto cuesta el viaje, y cuánto lleva de más para un imprevisto.
• Y una regla: el celular y la plata no se sacan en la calle sin necesidad.
Ejercicio 3, el plan para lo que salga mal:
Esto es lo que más se ensaya, con situaciones actuadas en sesión.
• Se pasó de parada: bajarse en la siguiente y avisar.
• Se quedó sin batería: llevar la dirección escrita en papel.
• No vino el ómnibus: cuánto espera antes de avisar, y a quién.
• Alguien lo aborda o se siente incómodo: entrar a un negocio, llamar.
• Y a quién llama, en orden: dos números escritos en papel y guardados.
Progresión:
• Si sale fácil: recorridos nuevos con transbordo, y organizar una salida completa (hora, plata, vuelta).
• Si no sale: acompañarlo desde una distancia cada vez mayor, en el mismo recorrido, las veces que haga falta.
Ojo con esto:
El ritmo lo marca cómo resuelve los imprevistos en el ensayo, no la edad ni las ganas de la familia. Y si hay dificultades importantes de orientación, comunicación o juicio de riesgo, se avanza con acompañamiento y se elige un recorrido corto y muy repetido.
Qué mirar:
Si reconoce la parada, si maneja el tiempo, si puede pedir información a un desconocido, cómo resuelve los imprevistos actuados. Criterio: el recorrido completo, ida y vuelta, hecho solo dos veces, con un imprevisto resuelto.
Cuánto y cada cuánto:
